func TestHFMockUsesScriptedToolsAndLocalFreeText(t *testing.T) {
	local := provider.NewMock(provider.Response{Content: "generated by local model"})
	mock := research.NewHFMockProvider(local, "worker-1", config.AgentConfig{Role: "baby-scientist"})
	response, err := mock.Generate(context.Background(), provider.Request{Messages: []provider.Message{{Role: "user", Content: "Research objective: deterministic scheduling"}}})
	if err != nil || response.Content != "generated by local model" || len(local.Requests()) != 1 {
		t.Fatalf("Generate() = %#v, %v", response, err)
	}
	chief := research.NewHFMockProvider(local, "chief", config.AgentConfig{Role: "chief-scientist"})
	response, err = chief.Generate(context.Background(), provider.Request{Messages: []provider.Message{{Role: "user", Content: "Research objective: deterministic scheduling"}}})
	if err != nil || len(response.ToolCalls) != 1 || response.ToolCalls[0].Name != "delegate_task" || len(local.Requests()) != 1 {
		t.Fatalf("scripted response = %#v, %v", response, err)
	}
}

