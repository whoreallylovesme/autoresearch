func TestHFMockRejectsUnboundedOrFabricatedNarration(t *testing.T) {
	local := provider.NewMock(provider.Response{Content: "### Sources Used\n1. Google Scholar and a fabricated book by R. J. Starnes"})
	mock := research.NewHFMockProvider(local, "worker-1", config.AgentConfig{Role: "baby-scientist"})
	response, err := mock.Generate(context.Background(), provider.Request{Messages: []provider.Message{{Role: "user", Content: "Research objective: deterministic scheduling"}}})
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(response.Content, "Starnes") || strings.Contains(response.Content, "Google Scholar") || strings.Contains(response.Content, "###") {
		t.Fatalf("fabricated narration was not rejected: %q", response.Content)
	}
	if !strings.Contains(response.Content, "no evidence") {
		t.Fatalf("safe fallback is missing: %q", response.Content)
	}
}
